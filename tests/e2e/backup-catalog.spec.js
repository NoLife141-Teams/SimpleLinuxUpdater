const { test, expect, password, ensureAuthenticatedSession } = require('./support/fixtures');
const fs = require('node:fs/promises');
const crypto = require('node:crypto');
test.use({ backupCatalogFixture: true, trace: 'off', screenshot: 'off', video: 'off' });

test('Admin catalog publishes, downloads encrypted bytes and reverifies with explicit identity resumption on mobile and keyboard', async ({ page, installation }) => {
    await ensureAuthenticatedSession(page);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('/admin');
    await page.locator('[data-admin-section-link="backup"]').click();
    const catalog = page.locator('#backup-archive-catalog');
    await expect(catalog).toContainText('No registered automated archives.');
    const initialDocumentWidth = await page.evaluate(() => document.documentElement.scrollWidth);
    await page.locator('#backup-automation-save').click();
    await expect(page.locator('#backup-automation-run')).toBeEnabled();
    await page.locator('#backup-automation-run').focus();
    await page.keyboard.press('Enter');
    await expect(catalog.locator('article')).toHaveCount(1);
    await expect(catalog).toContainText('Local availability: present');
    await expect(catalog).toContainText('Latest review: verified');
    await expect(catalog.getByRole('link', { name: 'View publication job' })).toHaveCount(1);
    const jobLink = await catalog.getByRole('link', { name: 'View publication job' }).getAttribute('href');
    expect((await page.request.get(jobLink)).status()).toBe(200);
    const catalogResponse = await page.request.get('/api/backup/archives');
    expect(catalogResponse.status()).toBe(200);
    expect(catalogResponse.headers()['cache-control']).toContain('no-store');
    const entry = (await catalogResponse.json()).archives[0];
    expect(JSON.stringify(entry)).not.toContain(installation.directory);
    expect(entry.published_at).toBeTruthy();
    const downloadEvent = page.waitForEvent('download');
    await catalog.getByRole('button', { name: 'Download encrypted' }).focus();
    await page.keyboard.press('Enter');
    const download = await downloadEvent;
    expect(download.suggestedFilename()).toBe('simplelinuxupdater-automated-backup.slubkp');
    const bytes = await fs.readFile(await download.path());
    expect(bytes.length).toBe(entry.size_bytes);
    expect(crypto.createHash('sha256').update(bytes).digest('hex')).toBe(entry.sha256);
    await download.delete();
    await expect(page.locator('#backup-catalog-result')).toContainText('Encrypted backup downloaded.');
    expect((await page.request.post('/__test/expire-reauthentication')).status()).toBe(204);
    let attempts = 0;
    page.on('request', request => { if (request.url().endsWith(`/archives/${entry.id}/verify`)) attempts++; });
    await catalog.getByRole('button', { name: 'Reverify', exact: true }).focus();
    await page.keyboard.press('Enter');
    await expect(page.locator('.reauthentication-dialog')).toBeVisible();
    expect(attempts).toBe(1);
    await page.locator('#reauthentication-password').fill(password);
    await page.keyboard.press('Enter');
    await expect(page.locator('#action-confirm-title')).toHaveText('Resume sensitive action');
    expect(attempts).toBe(1);
    await page.locator('#action-confirm-submit').focus();
    await page.keyboard.press('Enter');
    await expect(page.locator('#backup-catalog-result')).toContainText('Reverification succeeded. Active data was not replaced.');
    expect(attempts).toBe(2);
    await expect(catalog.getByRole('button', { name: 'Reverify', exact: true })).toBeEnabled();
    await catalog.locator('summary').focus();
    await page.keyboard.press('Enter');
    await expect(catalog.locator('code')).toBeVisible();
    await expect(catalog.locator('code')).toHaveText(entry.sha256);
    const catalogFits = await catalog.evaluate(el => {
        const right = el.getBoundingClientRect().right;
        return right <= innerWidth && [...el.querySelectorAll('*')].every(child => child.getBoundingClientRect().right <= innerWidth + 1);
    });
    expect(catalogFits).toBe(true);
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(initialDocumentWidth);
    expect((await page.request.get('/api/auth/identity')).status()).toBe(200);
    const auditResponse = await page.request.get('/api/audit-events?limit=100');
    const audit = await auditResponse.text();
    expect(audit).toContain('backup.download');
    expect(audit).toContain(entry.id);
    expect(audit).not.toContain('disposable-browser-catalog-passphrase');
    expect(audit).not.toContain(installation.directory);
    await catalog.getByRole('button', { name: 'Reverify', exact: true }).focus();
    expect((await page.request.post('/__test/expire-reauthentication')).status()).toBe(204);
    await page.keyboard.press('Enter');
    await expect(page.locator('.reauthentication-dialog')).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(page.locator('.reauthentication-dialog')).toHaveCount(0);
    await expect(page.locator('#backup-catalog-result')).toContainText('Backup action cancelled.');
    expect(attempts).toBe(3);
    await expect(catalog.getByRole('button', { name: 'Reverify', exact: true })).toBeFocused();
    await page.getByRole('link', { name: 'View archive events in audit' }).click();
    await expect(page).toHaveURL(/\/manage\?audit_target=automatic#audit-trail$/);
    await expect(page.locator('#audit-target-filter')).toHaveValue('automatic');
    await expect(page.locator('#audit-table')).toContainText('backup.download');
    await expect(page.locator('#audit-table')).toContainText('backup.verify');
});
